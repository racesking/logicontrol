// Narrow layout: the phone in flow, and a real tap on it.
import { spawn } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const prof = mkdtempSync(join(tmpdir(), 'lc-'));
const proc = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist', '--hide-scrollbars', '--remote-debugging-port=0', `--user-data-dir=${prof}`, '--window-size=390,844', 'about:blank']);
const ws = await new Promise((res) => { let b = ''; proc.stderr.on('data', (d) => { b += d; const m = b.match(/ws:\/\/[^\s]+/); if (m) res(m[0]); }); });
const page = (await (await fetch(`http://127.0.0.1:${new URL(ws).port}/json`)).json()).find((t) => t.type === 'page');
const sock = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((r) => { sock.onopen = r; });
let id = 0; const pend = new Map(); const errs = [];
sock.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } if (m.method === 'Runtime.exceptionThrown') errs.push(m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text); };
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pend.set(i, r); sock.send(JSON.stringify({ id: i, method, params })); });
const ev = async (x) => (await send('Runtime.evaluate', { expression: x, awaitPromise: true, returnByValue: true })).result?.result?.value;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await send('Page.enable'); await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: 'http://localhost:8137/' });
for (let i = 0; i < 80; i++) { await sleep(200); if (await ev('window.__frames > 3')) break; }
await ev(`document.getElementById('device').scrollIntoView({block:'center',behavior:'instant'})`);
await sleep(2500);
const s = await send('Page.captureScreenshot', { format: 'jpeg', quality: 88 });
writeFileSync(join(here, 'stk.jpg'), Buffer.from(s.result.data, 'base64'));
console.log('device rect', await ev(`(()=>{const r=document.getElementById('device').getBoundingClientRect();return [r.x,r.y,r.width,r.height].map(Math.round).join(',')})()`), '| inert', await ev(`document.getElementById('device').hasAttribute('inert')`), '| title pos', await ev(`getComputedStyle(document.querySelector('.home-title')).position`));
const b = await ev(`(()=>{const r=document.querySelector('.phone-ui [data-act="light"]').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2]})()`);
await send('Input.dispatchMouseEvent', { type: 'mousePressed', x: b[0], y: b[1], button: 'left', clickCount: 1 });
await send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: b[0], y: b[1], button: 'left', clickCount: 1 });
await sleep(1800);
console.log('tap light ->', await ev(`document.querySelector('.phone-ui [data-act="light"] em').textContent`), '| overflow', await ev('document.documentElement.scrollWidth-document.documentElement.clientWidth'));
console.log(errs.length ? 'errors: ' + errs.slice(0, 3).join(' | ') : 'no exceptions');
sock.close(); proc.kill(); process.exit(0);
